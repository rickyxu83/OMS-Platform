function applyDocumentLanguage(nextLanguage) {
  document.documentElement.lang = nextLanguage === 'hant' ? 'zh-Hant' : 'zh-CN'
}

applyDocumentLanguage(language.value)

function setLanguage(nextLanguage) {
  language.value = nextLanguage
  safeStorageSet(localStorage, STORAGE_KEY, nextLanguage)
  applyDocumentLanguage(nextLanguage)
}

function toTraditionalFallback(value) {
  let output = String(value || '')
  Object.entries(phraseMap).forEach(([source, target]) => {
    output = output.replaceAll(source, target)
  })
  return Array.from(output)
    .map((char) => charMap[char] || char)
    .join('')
}

function zh(value) {
  if (language.value !== 'hant') return value
  return textMap[value] || toTraditionalFallback(value)
}

export function usePreviewI18n() {
  return {
    language,
    languageLabel: computed(() => (language.value === 'hant' ? '繁體' : '简体')),
    setLanguage,
    zh,
  }
}
